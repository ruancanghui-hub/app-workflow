  static final sounds = <SoundAsset>[
    for (final source in _sources) _asset(source),
  ];

  static SoundAsset _asset(String source) {
    final parts = source.split('/');
    final group = parts.first;
    final stem = parts.last.replaceFirst(RegExp(r'\.(mp3|wav)$'), '');
    final id = 'moodist_${group}_$stem';
    final isSleep =
        _sleepGroups.contains(group) ||
        (group == 'animals' && _sleepAnimals.contains(stem)) ||
        (group == 'things' && _sleepThings.contains(stem));
    return SoundAsset(
      id: id,
      title: '${_groupTitle(group)} · ${_title(stem)}',
      subtitle: isSleep ? '睡眠 · 环境声景' : '冥想 · 专注环境声',
      tags: [isSleep ? '睡眠' : '冥想', _groupTitle(group)],
      isFree: true,
      durationMinutes: 30,
      playback: SoundPlaybackSource.bundled(
        'assets/sounds/$id.${source.split('.').last}',
      ),
    );
  }

